export type PixelIconName =
  | 'home' | 'career' | 'shop' | 'wealth' | 'social' | 'city' | 'profile' | 'cash' | 'calendar' | 'clock' | 'settings'
  | 'sleep' | 'book' | 'controller' | 'users' | 'house' | 'bag' | 'chart' | 'mail' | 'alert' | 'tag'
  | 'plane' | 'cup' | 'target' | 'spark' | 'user' | 'heart' | 'bolt' | 'smile';

/**
 * Shared micro icons use a 16×16 rect grid, matching the larger illustration
 * catalog. Each segment is an actual hard-edged pixel run, so navigation,
 * metadata, and footer icons share one denser 1-bit register instead of the
 * former 9×9 filled blobs or a smooth outline fallback.
 */
type PixelRect = readonly [x: number, y: number, width: number, height: number];

function rasterize(rects: readonly PixelRect[]): readonly string[] {
  const grid = Array.from({ length: 16 }, () => Array.from({ length: 16 }, () => '0'));
  rects.forEach(([x, y, width, height]) => {
    for (let row = y; row < y + height; row += 1) {
      for (let column = x; column < x + width; column += 1) {
        if (row >= 0 && row < 16 && column >= 0 && column < 16) grid[row][column] = '1';
      }
    }
  });
  return grid.map((row) => row.join(''));
}

