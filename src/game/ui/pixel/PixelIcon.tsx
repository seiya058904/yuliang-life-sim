const glyphs: Record<PixelIconName, readonly string[]> = Object.fromEntries(
  Object.entries(glyphRects).map(([name, rects]) => [name, rasterize(rects as readonly PixelRect[])])
) as Record<PixelIconName, readonly string[]>;

export function PixelIcon({ name, size = 18, className, ...props }: { name: PixelIconName; size?: number } & Omit<SVGProps<SVGSVGElement>, 'name'>) {
  const glyph = glyphs[name] ?? glyphs.settings;
  return <svg className={['pixel-icon', className].filter(Boolean).join(' ')} width={size} height={size} viewBox="0 0 16 16" fill="currentColor" stroke="none" strokeWidth="2.5" strokeLinecap="square" strokeLinejoin="miter" shapeRendering="crispEdges" aria-hidden="true" {...props}>
    {glyph.flatMap((row, rowIndex) => Array.from(row).map((cell, columnIndex) => cell === '1' ? <rect x={columnIndex} y={rowIndex} width="1" height="1" key={`${rowIndex}-${columnIndex}`} /> : null))}
  </svg>;
}
